CREATE TABLE raw_patients IF NOT EXISTS (
    Id String,
    BIRTHDATE String,
    DEATHDATE String,
    SSN String,
    DRIVERS String,
    PASSPORT String,
    PREFIX String,
    FIRST String,
    MIDDLE String,
    LAST String,
    SUFFIX String,
    MAIDEN String,
    MARITAL String,
    RACE String,
    ETHNICITY String,
    GENDER String,
    BIRTHPLACE String,
    ADDRESS String,
    CITY String,
    STATE String,
    COUNTY String,
    FIPS String,
    ZIP String,
    LAT String,
    LON String,
    HEALTHCARE_EXPENSES String,
    HEALTHCARE_COVERAGE String,
    INCOME String,
    _loaded_at Datetime DEFAULT now(),
    _source_file String DEFAULT 'patients.csv'
) ENGINE = MergeTree
ORDER BY Id;